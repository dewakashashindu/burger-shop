import { NextResponse } from "next/server";

import { replyEmail } from "@/lib/booking-notify";
import {
  stayGuestEmail,
  stayManagerEmail,
  staySms,
  tableGuestEmail,
  tableManagerEmail,
  tableSms,
} from "@/lib/booking-notify";
import { logoAttachment, managerEmail, mailConfigured, fromLine } from "@/lib/mail";

/**
 * GET /api/mail/preview — every booking message, laid out as the guest sees it.
 *
 * The four emails are rendered with the same functions a real booking calls, and
 * the emblem is inlined as a data URI so the page shows exactly what lands in an
 * inbox (where the logo arrives as an embedded `cid:` image). Sample data only:
 * booking number `T000000`, nothing is written or sent.
 *
 * This is the page to open when the wording changes, or before the SMTP details
 * are filled in.
 */
export async function GET() {
  const emblem = logoAttachment();
  const dataUri = emblem ? `data:image/png;base64,${emblem.content.toString("base64")}` : "";
  const inline = (html: string) => html.replace(/cid:mila-mirissa-logo/g, dataUri || "");
  const body = (html: string) => (html.match(/<body[^>]*>([\s\S]*)<\/body>/i) ?? [, html])[1];

  const table = {
    resId: "T000000",
    tableNo: "T3",
    area: "Terrace",
    date: "2026-11-12",
    from: "19:00",
    to: "21:00",
    pax: 2,
    name: "Nimal Perera",
    phone: "0771234567",
    email: "nimal@example.com",
    note: "By the window, please.",
  };

  const stay = {
    resId: "T000000",
    rooms: [{ name: "Garden Room" }],
    checkin: "2026-11-02",
    checkout: "2026-11-10",
    nights: 8,
    adults: 2,
    children: 0,
    arrival: "14:00",
    departure: "11:00",
    board: "breakfast",
    currency: "LKR",
    total: 196000,
    name: "Dewaka Shashindu",
    phone: "0771096131",
    email: "dewakashashindu@gmail.com",
    idNo: "2003025511",
    country: "Sri Lanka",
    requests: "",
  };

  const cards = [
    { who: "Guest", what: "Table booking — confirmation", mail: tableGuestEmail(table) },
    { who: `Restaurant · ${managerEmail()}`, what: "Table booking — the desk’s copy (email only, no text)", mail: tableManagerEmail(table) },
    { who: "Guest", what: "Room booking — confirmation", mail: stayGuestEmail(stay) },
    { who: `Restaurant · ${managerEmail()}`, what: "Room booking — the desk’s copy (email only, no text)", mail: stayManagerEmail(stay) },
  ];

  // The texts are the real builders — the same string the guest's phone gets.
  const texts = [
    { what: "Table booking", to: "94771234567", body: tableSms(table) },
    { what: "Room booking", to: "94771096131", body: staySms(stay) },
  ];

  const esc = (value: string) => value.replace(/&/g, "&amp;").replace(/</g, "&lt;");

  const page = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Mila Mirissa — booking messages, as they arrive</title></head>
<body style="margin:0;background:#efe9dc;font-family:Verdana,Arial,sans-serif;color:#2f2a22;">
<div style="max-width:760px;margin:0 auto;padding:28px 16px 60px;">
  <div style="font:600 11px/1.2 Verdana,Arial,sans-serif;letter-spacing:.18em;text-transform:uppercase;color:#8a7b63;">Preview · not sent</div>
  <h1 style="margin:10px 0 4px;font:400 30px/1.2 Georgia,serif;">What leaves the building</h1>
  <p style="margin:0 0 8px;font:400 14px/1.6 Georgia,serif;color:#5c5548;">
    Two texts and four emails per booking, generated by <code>lib/booking-notify.ts</code> from the booking
    that was just written — the wording is the wording.
  </p>
  <p style="margin:0 0 12px;font:400 13px/1.6 Verdana,sans-serif;color:#8a7b63;">
    The emblem sits at the top of all four emails and travels <i>inside</i> the message (an embedded
    <code>cid:</code> image, shown here as a data URI), so it appears even in inboxes that block images.
    The desk gets <b>email only</b> — <code>${esc(managerEmail())}</code>; texts go to the guest.
  </p>
  <div style="border:1px solid #d9cdb9;background:#faf7f1;border-radius:12px;padding:12px 14px;margin:0 0 22px;font:400 12px/1.7 Verdana,sans-serif;color:#5c5548;">
    <b style="color:#2f2a22;">In force right now</b><br>
    SMTP: <b>${mailConfigured() ? "configured" : "not configured — messages go to the server log"}</b><br>
    From: <code>${esc(fromLine() || "—")}</code><br>
    Desk copy: <code>${esc(managerEmail())}</code><br>
    Guest writes to: <code>${esc(replyEmail())}</code>
  </div>

  <h2 style="margin:26px 0 10px;font:600 11px/1.2 Verdana,sans-serif;letter-spacing:.16em;text-transform:uppercase;color:#8a7b63;">SMS · to the guest</h2>
  ${texts
    .map(
      (text) => `<div style="background:#fffdf8;border:1px solid #e7ded1;border-radius:14px;padding:14px 16px;margin-bottom:10px;">
    <div style="font:600 10px/1.2 Verdana,sans-serif;letter-spacing:.14em;text-transform:uppercase;color:#a2957f;margin-bottom:6px;">${esc(text.what)} · to ${esc(text.to)}</div>
    <div style="font:400 14px/1.6 Verdana,sans-serif;color:#2f2a22;">${esc(text.body)}</div>
  </div>`,
    )
    .join("")}

  ${cards
    .map(
      (card) => `<h2 style="margin:30px 0 10px;font:600 11px/1.2 Verdana,sans-serif;letter-spacing:.16em;text-transform:uppercase;color:#8a7b63;">${esc(card.who)} · ${esc(card.what)}</h2>
    <div style="border:1px dashed #cfc2ac;border-radius:16px;padding:10px;background:#efe9dc;">
      <div style="background:#fffdf8;border:1px solid #e7ded1;border-radius:12px;overflow:hidden;">
        <div style="padding:8px 14px;border-bottom:1px solid #e7ded1;font:400 12px/1.5 Verdana,sans-serif;color:#8a7b63;">
          <b style="color:#2f2a22;">Subject:</b> ${esc(card.mail.subject)}
        </div>
        ${body(inline(card.mail.html))}
        <div style="border-top:1px solid #e7ded1;padding:8px 14px;background:#faf7f1;font:400 11px/1.5 Verdana,sans-serif;color:#8a7b63;">
          <b style="color:#2f2a22;">Text version sent too:</b>
          <pre style="margin:6px 0 0;font:400 11px/1.5 ui-monospace,Menlo,Consolas,monospace;white-space:pre-wrap;color:#4b4438;">${esc(card.mail.text)}</pre>
        </div>
      </div>
    </div>`,
    )
    .join("")}

  <p style="margin:34px 0 0;font:400 12px/1.6 Verdana,sans-serif;color:#8a7b63;">
    Every text ends with the STOP line: <b>Reply STOP · 077 233 6233 · ${esc(replyEmail())}</b>.
    Sample data only — booking number <code>T000000</code>, nothing sent.
  </p>
</div>
</body></html>`;

  return new NextResponse(page, {
    headers: { "content-type": "text/html; charset=utf-8", "cache-control": "no-store" },
  });
}
